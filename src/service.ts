import { execFile } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import { mkdir, readFile, rm, stat, writeFile } from 'node:fs/promises';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';

/**
 * Runs the relay in the background as a per-user service on Windows (Task
 * Scheduler), macOS (launchd), and Linux (systemd user unit). None of these
 * need administrator rights. Each starts the relay when the user logs in and
 * restarts it if it exits unexpectedly.
 */

const run = promisify(execFile);

export const SERVICE_NAME = 'crosschat-relay';
const WINDOWS_TASK = 'Crosschat Relay';
const MAC_LABEL = 'dev.crosschat.relay';

export interface ServiceConfig {
  /** The Node.js executable that runs the relay. */
  nodePath: string;
  /** Absolute path to the relay's entry script (dist/index.js). */
  scriptPath: string;
  /** Extra environment for the relay process (for example ELECTRON_RUN_AS_NODE). */
  env?: Record<string, string>;
  dataDir: string;
  port: number;
  host: string;
  allowedHosts?: string;
  logFile: string;
  installedAt: string;
}

export interface ServiceStatus {
  platform: NodeJS.Platform;
  installed: boolean;
  /** Whether the OS reports the service as running. */
  running: boolean;
  /** Whether the relay answers its health check. */
  healthy: boolean;
  config?: ServiceConfig;
  dashboardUrl?: string;
}

/**
 * Where the relay keeps its data and service files when run as a service.
 *
 * On Windows this is %USERPROFILE%\.crosschat-relay rather than AppData:
 * packaged (MSIX) apps such as some terminals and editors have their writes to
 * AppData redirected into a private copy, which Task Scheduler cannot see.
 */
export function appDirectory(platform: NodeJS.Platform = process.platform, env: NodeJS.ProcessEnv = process.env): string {
  if (platform === 'win32') return join(env.USERPROFILE ?? homedir(), `.${SERVICE_NAME}`);
  if (platform === 'darwin') return join(homedir(), 'Library', 'Application Support', SERVICE_NAME);
  return join(env.XDG_DATA_HOME ?? join(homedir(), '.local', 'share'), SERVICE_NAME);
}

const configPath = () => join(appDirectory(), 'service.json');
const stopFlagPath = (dataDir: string) => join(dataDir, 'service.stopped');
export const pidFilePath = (dataDir: string) => join(dataDir, 'relay.pid');

export function relayArguments(config: ServiceConfig): string[] {
  return [
    config.scriptPath,
    '--port',
    String(config.port),
    '--host',
    config.host,
    '--data-dir',
    config.dataDir,
    '--log-file',
    config.logFile,
    ...(config.allowedHosts ? ['--allowed-hosts', config.allowedHosts] : []),
  ];
}

